test('FINISH stamps the clock once and is idempotent', async ({ page }) => {
  await startSession(page, 'Day 1 Push', `${MARK} finish`)
  await page.getByRole('button', { name: 'FINISH SESSION' }).click()
  await expect(page.getByText('Finished', { exact: true })).toBeVisible()

  const first = await withDb(async (c) => {
    const r = await c.query<{ completed_at: string }>(
      `select completed_at::text from workout_sessions where name = $1`,
      [`${MARK} finish`],
    )
    return r.rows[0]!.completed_at
  })

  // Tapping again must not move the time, or the duration would change per tap.
  await page.reload()
  await page.getByText('Finished', { exact: true }).waitFor()
  await withDb((c) => c.query(`select finish_session(id) from workout_sessions where name = $1`, [`${MARK} finish`]))
  const second = await withDb(async (c) => {
    const r = await c.query<{ completed_at: string }>(
      `select completed_at::text from workout_sessions where name = $1`,
      [`${MARK} finish`],
    )
    return r.rows[0]!.completed_at
  })
  expect(second).toBe(first)
})
