/**
 * P3-3: the live session, against real Postgres.
 *
 * The two claims worth the setup cost are the offline ones. **AC-2.1**: a set saves
 * and renders locked in under 200 ms with no signal. **AC-2.9**: start, log sets,
 * close the app, reopen — every set present and synced exactly once. Everything
 * else on this screen is comfort; those two are why it exists.
 */
const TOKEN = process.env.APP_ACCESS_TOKEN!
const MARK = 'ZZTest'

const cleanup = () =>
  withDb(async (c) => {
    await c.query(
      `delete from workout_sets where session_id in
         (select id from workout_sessions where name like $1)`,
      [`${MARK}%`],
    )
    await c.query(`delete from workout_sessions where name like $1`, [`${MARK}%`])
  }).then(dropUnreferencedPlans)

test.beforeEach(cleanup)
test.afterAll(cleanup)
test.afterAll(closeDb)

const setsOf = (name: string) =>
  withDb(async (c) => {
    const r = await c.query<{
      id: string
      set_index: number
      kind: string
      weight_kg: string | null
      reps: number | null
      duration_sec: number | null
      volume_kg: string | null
      side: string | null
    }>(
      `select s.id, s.set_index, s.kind::text, s.weight_kg, s.reps, s.duration_sec, s.volume_kg, s.side
       from workout_sets s join workout_sessions w on w.id = s.session_id
       where w.name = $1 order by s.position, s.set_index`,
      [name],
    )
    return r.rows
  })

/** Builds a session through the UI and returns its url. */
async function startSession(
  page: import('@playwright/test').Page,
  template: string,
  name: string,
): Promise<string> {
  await page.goto(`/train/plan?k=${TOKEN}`)
  await page.getByRole('heading', { name: 'New session' }).waitFor()
  await page.getByLabel('Template').click()
  await page.getByRole('option', { name: template, exact: true }).click()
  await page.getByLabel('Session name').fill(name)
  await page.getByRole('button', { name: 'START SESSION' }).click()
  await page.waitForURL(/\/train\/session\//)
  return page.url()
}

test('a set commits, locks, and starts the rest timer', async ({ page }) => {
  await startSession(page, 'Day 1 Push', `${MARK} push`)

  const weight = page.getByLabel(/KG for set 1 of Shoulder Press Machine/)
  await weight.waitFor()
  // PREV is populated from the start, showing `—` with no history at this gym.
  await expect(page.getByText('—').first()).toBeVisible()

  await weight.fill('57.5')
  await page.getByLabel(/Reps for set 1 of Shoulder Press Machine/).fill('12')
  await page.getByRole('checkbox', { name: /Save set 1 of Shoulder Press Machine/ }).click()

  // The row locks: its inputs become text and the checkbox reads as saved.
  await expect(page.getByRole('checkbox', { name: /Unsave set 1 of .*/ })).toBeVisible()
  // Rest starts automatically on commit (US-2.10) — one less tap with both hands busy.
  await expect(page.getByRole('timer', { name: /Rest, \d+ seconds remaining/ })).toBeVisible()

  await expect.poll(() => setsOf(`${MARK} push`)).toHaveLength(1)
  const [saved] = await setsOf(`${MARK} push`)
  expect(Number(saved!.weight_kg)).toBe(57.5)
  expect(saved!.reps).toBe(12)
  // Generated by Postgres, never sent by the client.
  expect(Number(saved!.volume_kg)).toBe(690)
})

test('unchecking a set unlocks it; re-ticking saves the correction', async ({ page }) => {
  await startSession(page, 'Day 1 Push', `${MARK} edit set`)

  await page.getByLabel(/KG for set 1 of Shoulder Press Machine/).fill('50')
  await page.getByLabel(/Reps for set 1 of Shoulder Press Machine/).fill('10')
  await page.getByRole('checkbox', { name: /Save set 1 of Shoulder Press Machine/ }).click()
  await expect(page.getByRole('checkbox', { name: /Unsave set 1 of .*/ })).toBeVisible()
  // Inputs become text while locked.
  await expect(page.getByLabel(/KG for set 1 of Shoulder Press Machine/)).toHaveCount(0)

  await page.getByRole('checkbox', { name: /Unsave set 1 of Shoulder Press Machine/ }).click()
  // Unlocked: inputs return with the previous values, rest does not restart from a correction.
  await expect(page.getByLabel(/KG for set 1 of Shoulder Press Machine/)).toHaveValue('50')
  await page.getByLabel(/KG for set 1 of Shoulder Press Machine/).fill('55')
  await page.getByLabel(/Reps for set 1 of Shoulder Press Machine/).fill('8')
  await page.getByRole('checkbox', { name: /Save set 1 of Shoulder Press Machine/ }).click()
  await expect(page.getByRole('checkbox', { name: /Unsave set 1 of .*/ })).toBeVisible()

  await page.bringToFront()
  await expect.poll(async () => {
    const rows = await setsOf(`${MARK} edit set`)
    return rows.length === 1 ? Number(rows[0]!.weight_kg) : null
  }, { timeout: 20_000 }).toBe(55)
  const [corrected] = await setsOf(`${MARK} edit set`)
  expect(corrected!.reps).toBe(8)
  expect(Number(corrected!.volume_kg)).toBe(440)
})

test('the session strip counts volume from eligible sets only (AC-2.4)', async ({ page }) => {
  await startSession(page, 'Day 3 Legs', `${MARK} legs`)

  await page.getByLabel(/KG for set 1 of Leg Press/).fill('100')
  await page.getByLabel(/Reps for set 1 of Leg Press/).fill('10')
  await page.getByRole('checkbox', { name: /Save set 1 of Leg Press/ }).click()
  await expect(page.getByRole('checkbox', { name: /Unsave set 1 of .*/ }).first()).toBeVisible()

  // A plank has no weight input at all — only seconds.
  await expect(page.getByLabel(/Seconds for set 1 of Plank/)).toBeVisible()
  await page.getByLabel(/Seconds for set 1 of Plank/).fill('45')
  await page.getByRole('checkbox', { name: /Save set 1 of Plank/ }).click()

  // Two sets, but the plank adds no kilograms — the spreadsheet's mistake, refused.
  await expect(page.getByText('1,000')).toBeVisible()
  await expect(page.getByText(/carry no volume by definition/)).toBeVisible()

  /**
   * `bringToFront()` fires the visibilitychange the sync queue flushes on — the same
   * trigger AC-2.9 below leans on deliberately, and the one iOS actually relies on.
   *
   * Without it this passed alone and failed in the full run: the commit path is
   * local-first by design, so a set waits in IndexedDB until a flush trigger arrives, and
   * across a long suite none reliably did inside the poll window. Raising the timeout did
   * not help, because nothing was going to happen — the fix is to trigger the flush, not
   * to wait longer for one.
   */
  await page.bringToFront()
  await expect.poll(() => setsOf(`${MARK} legs`), { timeout: 20_000 }).toHaveLength(2)
  const rows = await setsOf(`${MARK} legs`)
  const plank = rows.find((r) => r.duration_sec !== null)!
  expect(plank.volume_kg).toBeNull()
})

