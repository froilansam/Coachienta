test('AC-2.1 — a set locks in under 200 ms with no signal', async ({ page, context }) => {
  await startSession(page, 'Day 1 Push', `${MARK} offline`)
  await page.getByLabel(/KG for set 1 of Shoulder Press Machine/).waitFor()

  await context.setOffline(true)

  await page.getByLabel(/KG for set 1 of Shoulder Press Machine/).fill('60')
  await page.getByLabel(/Reps for set 1 of Shoulder Press Machine/).fill('8')

  /**
   * Measured around the commit itself. The path is one IndexedDB transaction and a
   * re-render from Dexie — there is nothing to await on the network, which is the
   * whole design of the screen.
   */
  const started = Date.now()
  await page.getByRole('checkbox', { name: /Save set 1 of Shoulder Press Machine/ }).click()
  await page.getByRole('checkbox', { name: /Set 1 saved/ }).waitFor()
  const elapsed = Date.now() - started
  expect(elapsed).toBeLessThan(200)

  await context.setOffline(false)
})

test('AC-2.9 — sets logged offline hold in the queue and sync exactly once', async ({
  page,
  context,
}) => {
  await startSession(page, 'Day 2 Pull', `${MARK} pull offline`)
  await page.getByLabel(/Reps for set 1 of Pull-Ups/).waitFor()

  await context.setOffline(true)

  // Pull-Ups are bodyweight: reps alone is a complete set.
  await page.getByLabel(/Reps for set 1 of Pull-Ups/).fill('8')
  await page.getByRole('checkbox', { name: /Save set 1 of Pull-Ups/ }).click()
  await page.getByRole('checkbox', { name: /Set 1 saved/ }).waitFor()

  await page.getByLabel(/Reps for set 2 of Pull-Ups/).fill('7')
  await page.getByRole('checkbox', { name: /Save set 2 of Pull-Ups/ }).click()
  await expect(page.getByRole('checkbox', { name: /Set 2 saved/ })).toBeVisible()

  // Both are on screen and locked, and NEITHER has reached Postgres — the queue is
  // holding them.
  expect(await setsOf(`${MARK} pull offline`)).toHaveLength(0)

  /**
   * Let the BROWSER fire its own `online` event rather than dispatching one from
   * `page.evaluate` — evaluating right after `setOffline(false)` raced a navigation
   * and died with "Execution context was destroyed". `bringToFront` also triggers
   * the visibilitychange flush, which is the trigger iOS actually relies on.
   */
  await context.setOffline(false)
  await page.bringToFront()
  await expect.poll(() => setsOf(`${MARK} pull offline`), { timeout: 20_000 }).toHaveLength(2)

  // Exactly once: a replayed flush upserts on the client-generated id.
  await page.reload()
  await page.bringToFront()
  await page.waitForTimeout(2000)
  expect(await setsOf(`${MARK} pull offline`)).toHaveLength(2)
})

/**
 * The other half of AC-2.9 — "app closed, reopened" WHILE OFFLINE — cannot be
 * tested, and not because of anything on this screen.
 *
 * There is no cached app shell: `__SW_MANIFEST` carries only `_next/static/*`,
 * `@serwist/next` ignores `additionalPrecacheEntries`, and its `defaultCache` is a
 * single NetworkOnly passthrough. `page.reload()` offline therefore fails with
 * `net::ERR_FAILED` before any of our code runs. The same gap is already recorded
 * as `test.fixme` in `e2e/offline-sync.spec.ts`.
 *
 * The queued sets themselves are unaffected: they live in IndexedDB and upload on
 * the next focus, which the test above proves.
 */
test.fixme('AC-2.9 — reopening the app offline restores the logged sets', async ({
  page,
  context,
}) => {
  await startSession(page, 'Day 2 Pull', `${MARK} reopen`)
  await context.setOffline(true)
  await page.getByLabel(/Reps for set 1 of Pull-Ups/).fill('8')
  await page.getByRole('checkbox', { name: /Save set 1 of Pull-Ups/ }).click()
  await page.reload()
  await expect(page.getByRole('checkbox', { name: /Set 1 saved/ })).toBeVisible()
})

